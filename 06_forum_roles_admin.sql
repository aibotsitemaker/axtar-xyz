create or replace function public.admin_replace_quiz_questions(p_quiz_id uuid, p_questions jsonb)
returns void language plpgsql security definer set search_path=public,pg_temp as $$
begin
  if jsonb_typeof(p_questions) <> 'array' or jsonb_array_length(p_questions) < 1 or jsonb_array_length(p_questions) > 100 then
    raise exception 'Sual siyahısı yanlışdır';
  end if;
  if exists(select 1 from public.quiz_attempts where quiz_id=p_quiz_id) then
    raise exception 'Cavablanmış sınağın suallarını dəyişmək olmaz; nəticə tarixçəsi qorunur';
  end if;
  if not exists(select 1 from public.quizzes where id=p_quiz_id) then raise exception 'Sınaq tapılmadı'; end if;
  delete from public.quiz_questions where quiz_id=p_quiz_id;
  insert into public.quiz_questions(quiz_id,position,question_text,options,correct_index,explanation)
  select p_quiz_id, item.ordinality::integer, item.value->>'question_text', item.value->'options',
    (item.value->>'correct_index')::integer, coalesce(item.value->>'explanation','')
  from jsonb_array_elements(p_questions) with ordinality as item(value,ordinality);
end; $$;
revoke all on function public.admin_replace_quiz_questions(uuid,jsonb) from public,anon,authenticated;
grant execute on function public.admin_replace_quiz_questions(uuid,jsonb) to service_role;

