create or replace function public.notify_forum_reply()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare owner_id uuid;
begin
  select author_id into owner_id from public.forum_topics where id=new.topic_id;
  if owner_id is not null and owner_id<>new.author_id then
    insert into public.forum_notifications(user_id,topic_id,reply_id,actor_id) values(owner_id,new.topic_id,new.id,new.author_id);
  end if;
  if new.parent_id is not null then
    insert into public.forum_notifications(user_id,topic_id,reply_id,actor_id)
      select author_id,new.topic_id,new.id,new.author_id from public.forum_replies
      where id=new.parent_id and author_id<>new.author_id and author_id is distinct from owner_id;
  end if;
  return new;
end; $$;
