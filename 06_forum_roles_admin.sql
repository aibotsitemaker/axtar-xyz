create or replace function public.guard_forum_report()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare total integer;
begin
  if new.reporter_id<>auth.uid() and not public.is_admin() then raise exception 'Şikayəti yalnız öz hesabınızdan göndərə bilərsiniz'; end if;
  if tg_op='INSERT' and not public.is_admin() then
    perform pg_advisory_xact_lock(hashtextextended(new.reporter_id::text, 3));
    select count(*) into total from public.forum_reports where reporter_id=new.reporter_id and created_at>now()-interval '1 hour';
    if total>=10 then raise exception 'Saatlıq şikayət limiti dolub'; end if;
    new.status:='open'; new.reviewed_by:=null; new.reviewed_at:=null; new.created_at:=now();
  end if;
  return new;
end; $$;
drop trigger if exists forum_reports_guard on public.forum_reports;
create trigger forum_reports_guard before insert or update on public.forum_reports for each row execute function public.guard_forum_report();

