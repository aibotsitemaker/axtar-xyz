create or replace function public.forum_search_topics(p_query text default null, p_category_id bigint default null, p_sort text default 'recent', p_offset integer default 0, p_limit integer default 30)
returns setof public.forum_topics language sql stable set search_path=public,pg_temp as $$
  select t.* from public.forum_topics t
  where t.deleted_at is null
    and (p_category_id is null or t.category_id=p_category_id)
    and (nullif(btrim(p_query),'') is null or position(lower(left(btrim(p_query),160)) in lower(t.title || ' ' || t.body)) > 0)
  order by t.is_pinned desc,
    case when p_sort='replies' then (select count(*) from public.forum_replies r where r.topic_id=t.id and r.deleted_at is null) end desc,
    case when p_sort='new' then t.created_at end desc,
    t.updated_at desc
  offset greatest(0,least(p_offset,100000)) limit greatest(1,least(p_limit,60));
$$;
revoke all on function public.forum_search_topics(text,bigint,text,integer,integer) from public;
grant execute on function public.forum_search_topics(text,bigint,text,integer,integer) to anon,authenticated;

create or replace function public.guard_forum_write()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare n integer; prior text;
begin
  if tg_op='INSERT' and not public.is_admin() then
    if tg_table_name='forum_topics' then
      new.created_at:=now(); new.updated_at:=now(); new.is_pinned:=false; new.is_locked:=false; new.deleted_at:=null;
      if not exists(select 1 from public.forum_categories c where c.id=new.category_id and c.is_active) then raise exception 'Kateqoriya aktiv deyil'; end if;
    else
      new.created_at:=now(); new.updated_at:=now(); new.deleted_at:=null;
    end if;
  elsif tg_op='UPDATE' then
    new.updated_at:=now();
  end if;
  if tg_op='UPDATE' and not public.is_admin() then
    if tg_table_name='forum_topics' then
      if new.author_id<>old.author_id or new.is_pinned<>old.is_pinned or new.is_locked<>old.is_locked or (new.deleted_at is distinct from old.deleted_at and not (old.author_id=auth.uid() and old.deleted_at is null and new.deleted_at is not null)) or new.created_at<>old.created_at then
        raise exception 'Bu mövzu əməliyyatına icazə yoxdur';
      end if;
    elsif tg_table_name='forum_replies' then
      if new.author_id<>old.author_id or new.topic_id<>old.topic_id or new.parent_id is distinct from old.parent_id or (new.deleted_at is distinct from old.deleted_at and not (old.author_id=auth.uid() and old.deleted_at is null and new.deleted_at is not null)) or new.created_at<>old.created_at then
        raise exception 'Bu cavab əməliyyatına icazə yoxdur';
      end if;
    end if;
  end if;
  if char_length(btrim(new.body)) < 1 then raise exception 'Mətn boş ola bilməz'; end if;
  if tg_table_name='forum_topics' then
    if char_length(btrim(new.title)) not between 8 and 160 or char_length(btrim(new.body)) > 12000 then raise exception 'Mövzu başlığı və ya mətni limitdən kənardır'; end if;
    if tg_op='INSERT' then
      perform pg_advisory_xact_lock(hashtextextended(new.author_id::text, 1));
      select count(*) into n from public.forum_topics where author_id=new.author_id and created_at>now()-interval '1 hour';
      if n>=10 then raise exception 'Saatlıq mövzu limiti dolub'; end if;
      select body into prior from public.forum_topics where author_id=new.author_id and md5(lower(btrim(body)))=md5(lower(btrim(new.body))) and created_at>now()-interval '1 day' limit 1;
      if prior is not null then raise exception 'Eyni məzmun təkrar göndərilə bilməz'; end if;
    end if;
  else
    if char_length(btrim(new.body))>6000 then raise exception 'Cavab çox uzundur'; end if;
    if new.parent_id is not null and not exists(select 1 from public.forum_replies p where p.id=new.parent_id and p.topic_id=new.topic_id and p.parent_id is null) then
      raise exception 'Cavab yalnız mövzudakı əsas cavaba bağlana bilər';
    end if;
    if tg_op='INSERT' then
      perform pg_advisory_xact_lock(hashtextextended(new.author_id::text, 2));
      select count(*) into n from public.forum_replies where author_id=new.author_id and created_at>now()-interval '1 hour';
      if n>=30 then raise exception 'Saatlıq cavab limiti dolub'; end if;
      select body into prior from public.forum_replies where author_id=new.author_id and md5(lower(btrim(body)))=md5(lower(btrim(new.body))) and created_at>now()-interval '1 day' limit 1;
      if prior is not null then raise exception 'Eyni cavab təkrar göndərilə bilməz'; end if;
    end if;
  end if;
  return new;
end; $$;
