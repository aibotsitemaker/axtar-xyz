create or replace function public.forum_topic_stats(p_topic_ids uuid[])
returns table(topic_id uuid, reply_count bigint, last_author_id uuid, last_reply_at timestamptz)
language sql stable set search_path=public,pg_temp as $$
  select r.topic_id, count(*)::bigint,
         (array_agg(r.author_id order by r.created_at desc))[1], max(r.created_at)
  from public.forum_replies r
  where r.topic_id=any(p_topic_ids) and r.deleted_at is null
