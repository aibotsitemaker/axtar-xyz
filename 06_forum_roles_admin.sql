create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path=public,pg_temp as $$
declare requested_type text;
begin
  requested_type := new.raw_user_meta_data ->> 'user_type';
  if requested_type not in ('teacher','student','university_student') then requested_type := 'student'; end if;
  insert into public.profiles (id, full_name, user_type)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email,'@',1)), requested_type)
  on conflict (id) do update set user_type=excluded.user_type;
  return new;
end; $$;
